# 문구 선택 · 지연 — 전부 reply_id 해시 기반(결정적)
# ══════════════════════════════════════════════════════════════════

def _hash_int(seed):
    return int(hashlib.sha256(seed.encode("utf-8")).hexdigest(), 16)


def choose_reply(reply_id, pool, recent=()):
    """reply_id 해시로 문구를 고르되 최근에 쓴 문구는 피한다.

    random을 쓰지 않는 이유: 명령이 재실행돼도 같은 댓글에는 같은 문구가 나와야
    "이 댓글에 무엇을 보냈나"를 나중에 재현·검증할 수 있다.

    recent는 최신순 목록. 문구 수보다 최근 발송이 많으면 전부 걸리므로,
    그때는 그중 가장 오래전에 쓴 문구를 고른다.
    """
    recent = list(recent)
    start = _hash_int(reply_id) % len(pool)
    order = [pool[(start + i) % len(pool)] for i in range(len(pool))]
    for cand in order:
        if cand not in recent:
            return cand
    return max(order, key=recent.index)


def reply_delay_minutes(reply_id, lo, hi):
    """댓글 작성 후 몇 분 뒤에 답할지 (lo~hi분).

    즉답은 봇 티가 난다. 지연도 해시로 정해야 재실행 시 발송 시각이 흔들리지 않는다.
    """
    return lo + _hash_int("delay:" + reply_id) % (hi - lo + 1)


