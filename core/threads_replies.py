def classify(text):
    """댓글 본문 -> (버킷, 근거). 버킷은 "A"/"B"/"C".

    근거는 ThreadsReply.bucket_reason에 그대로 저장한다. 나중에 "이 댓글을 왜
    A로 봤는가"를 사람이 되짚을 수 있어야 자동 응답 범위를 검증할 수 있다.
    """
    text = (text or "").strip()
    if not text:
        # 이미지만 달린 댓글 등. 인사로 오인해 답하지 않도록 B로 둔다.
        return "B", "B:빈 본문"

    # ① C 먼저 — 하나라도 걸리면 나머지는 볼 것도 없다
    for name, pat in C_PATTERNS:
        m = pat.search(text)
        if m:
            return "C", f"C:{name}({m.group(0).strip()})"

    compact = re.sub(r"\s+", "", text)
    is_question = bool(QUESTION.search(text))

    # ② A — 세 경로 중 하나. 어느 쪽이든 질문 내용을 반영하지 않는 답이 가능해야 한다
    if not _HAS_WORD.search(text):
        return "A", "A:짧은반응(이모지·자음만)"

    if len(compact) <= SHORT_REACTION_LEN and not is_question:
        return "A", f"A:짧은반응({len(compact)}자)"

    if len(compact) <= A_MAX_LEN:
        m = A_SERVICE.search(text)
        if m:
            blocked = A_BLOCK.search(text)
            if blocked:
                # 안내로 끝날 질문이 아니다 — 사람이 답해야 한다
                return "B", f"B:서비스질문에 투자용어({blocked.group(0)})"
            return "A", f"A:서비스안내({m.group(0).strip()})"

        m = A_GREET.search(text)
        if m and not is_question:
            return "A", f"A:인사감사({m.group(0).strip()})"
        if m and is_question:
            return "B", f"B:인사와 질문 혼재({m.group(0).strip()})"

    # ③ 나머지는 전부 사람이 답한다
    return "B", "B:기본(A·C 신호 없음)"


def is_service_reason(reason):
    """분류 근거가 서비스 안내인지 — 어느 문구 묶음을 쓸지 고르는 데만 쓴다."""
    return "서비스안내" in (reason or "")


