def is_approved(text):
    """발송 직전 최종 확인 — 승인된 상수 문구가 아니면 내보내지 않는다.

    분류기나 문구 선택에 버그가 나도 즉흥 문장이 나가는 일만은 막는 최후 방어선.
    """
    return text in _APPROVED


